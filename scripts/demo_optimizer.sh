#!/usr/bin/env bash
# Демонстрация оптимизаций AST: для каждого случая показывается дерево
# до оптимизации (--parse-only) и после (без флагов).
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="$ROOT_DIR/fcompiler"

if [[ ! -x "$BIN" ]]; then
    echo "Сначала соберите проект: task" >&2
    exit 1
fi

demo() {
    local title="$1" src="$2"
    printf '\n\033[1m%s\033[0m\n' "$title"
    printf '  до:    %s\n' "$(printf '%s' "$src" | "$BIN" --parse-only 2>&1 | paste -sd' ')"
    printf '  после: %s\n' "$(printf '%s' "$src" | "$BIN"              2>&1 | paste -sd' ')"
}

echo "=============================================="
echo " Оптимизации, изменяющие AST"
echo "=============================================="

demo "1. Свёртка констант (арифметика)" \
     '(plus (times 2 3) (minus 10 4))'

demo "1b. Свёртка констант (сравнения и логика)" \
     '(and (less 1 2) (greater 5 3))'

demo "2. Отбрасывание мёртвой ветки cond" \
     '(cond (less 1 2) 100 200)'

demo "3. Удаление цикла с ложным условием" \
     '(while (greater 1 2) (setq x 1))'

demo "4. Удаление недостижимого кода после return" \
     '(func f (n) (return n) (setq n 999) (plus n 1))'

demo "5. Свёртка операций над списками" \
     '(head (quote (1 2 3)))'

demo "5b. cons над литеральным списком" \
     '(cons 0 (quote (1 2)))'

demo "6. Короткое замыкание and/or" \
     '(or true (plus 1 2))'

echo
echo "=============================================="
echo " Границы: где оптимизатор обязан остановиться"
echo "=============================================="

demo "Нечистый аргумент не выбрасывается (setq)" \
     '(prog (x) (setq x 0) (and false (setq x 1)))'

demo "Возможное деление на ноль не выбрасывается" \
     '(prog (y) (setq y 0) (and false (divide 1 y)))'

demo "Предикат над переменной — только во время выполнения" \
     '(prog (x) (setq x 5) (isint x))'

demo "Процитированные данные не вычисляются" \
     '(quote (plus 1 2))'

echo
echo "=============================================="
echo " Повторные проходы до неподвижной точки"
echo "=============================================="

# проход 1: (equal 1 1) -> true
# проход 2: (cond true 2 3) -> 2
# проход 3: (plus 1 2) -> 3
demo "Три прохода: свёртка -> ветка -> снова свёртка" \
     '(plus 1 (cond (equal 1 1) 2 3))'
